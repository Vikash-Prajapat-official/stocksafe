// Derives prisma/schema.sqlite.prisma from prisma/schema.prisma so the two can never drift apart.
// Differences: the provider, no @db.Date (SQLite has one DateTime type), and no autoincrement() on non-key columns
// (SQLite only auto-numbers primary keys; src/lib/seq.ts assigns those numbers instead).
import { readFileSync, writeFileSync } from "node:fs";

const src = readFileSync("prisma/schema.prisma", "utf8").replace(/\r\n/g, "\n");
let out = src
  .replace('provider = "postgresql"', 'provider = "sqlite"')
  .replace(/\s+@db\.Date/g, "")
  .replace(/@default\(autoincrement\(\)\)/g, "@default(0)");
out =
  "// GENERATED by scripts/make-sqlite-schema.mjs from schema.prisma. Do not edit by hand.\n// Single-PC mode: same tables, stored in one SQLite file.\n\n" + out;
writeFileSync("prisma/schema.sqlite.prisma", out);
console.log("wrote prisma/schema.sqlite.prisma");
